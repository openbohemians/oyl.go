#!/bin/sh
# Vendor Oyl's C sources into c/ from a checkout, at its committed HEAD or
# at the given ref (a release tag), recording the commit in c/COMMIT. cgo
# compiles only the package's own directory, so each C source also gets a
# one-line wrapper there that includes it.
#
#   scripts/sync-oyl.sh path/to/oyl [ref]
set -eu
src=${1:?usage: scripts/sync-oyl.sh path/to/oyl [ref]}
ref=${2:-HEAD}
root="$(cd "$(dirname "$0")/.." && pwd)"
dest="$root/c"
rm -rf "$dest"
mkdir -p "$dest"
git -C "$src" archive "$ref" src include LICENSE | tar -x -C "$dest"
git -C "$src" log -1 --format='%H %cs %s' "$ref" > "$dest/COMMIT"
rm -f "$root"/oyl_*.c
for f in "$dest"/src/*.c; do
    b=$(basename "$f")
    printf '/* Generated by scripts/sync-oyl.sh: cgo compiles only this directory. */\n#include "c/src/%s"\n' "$b" > "$root/$b"
done
echo "vendored: $(cat "$dest/COMMIT")"
